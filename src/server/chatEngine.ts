import { GoogleGenAI } from "@google/genai";

export interface ChatMessage {
  role: "user" | "model";
  text: string;
}

export interface ChatRequest {
  messages: ChatMessage[];
  model?: "gemini-3.8-flash" | "gemini-3.1-flash-lite";
  useSearch?: boolean;
  rolePersona?: "threat_hunter" | "incident_responder" | "cyber_advisor";
}

let aiClient: GoogleGenAI | null = null;
function getAiClient(): GoogleGenAI | null {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) return null;
  if (!aiClient) {
    aiClient = new GoogleGenAI({
      apiKey,
      httpOptions: {
        headers: {
          "User-Agent": "aistudio-build",
        },
      },
    });
  }
  return aiClient;
}

const SYSTEM_INSTRUCTIONS = {
  threat_hunter: `You are ScamShield Threat Hunter & SecOps Lead, an elite cybersecurity forensic analyst.
Your mission is to provide deep, technically rigorous analysis of phishing schemes, social engineering vectors, lookalike domains, deceptive QR quishing traps, and malicious communication payloads.
Always structure responses clearly with:
- Threat Classification & Attack Vector
- Behavioral & Technical Red Flags (IoCs)
- Real-world Impact & Attacker Objectives
- Tactical Recommendations (Quarantine, Blocklist, Reporting)
Be direct, authoritative, and security-focused.`,

  incident_responder: `You are ScamShield Incident Response Commander, a high-urgency crisis containment specialist.
When a user suspects or confirms they interacted with a scam or malicious payload (e.g. clicked a link, entered credentials, downloaded a file, or sent money), guide them through immediate emergency containment protocols:
1. Immediate Isolation & Disconnect
2. Credential Rotation & Session Revocation
3. Financial Institution & Bank Lockdowns
4. Multi-Factor Authentication (MFA) Re-securing
5. Device Scanning & Evidence Collection
Prioritize actionable, step-by-step triage ordered from most critical to follow-up.`,

  cyber_advisor: `You are ScamShield Cyber Defense Advisor, a helpful and approachable personal security strategist.
Explain deceptive tactics, AI-generated voice cloning, smishing, quishing, and scam psychology in clear, accessible language without excessive jargon.
Empower the user with intuitive defense habits, zero-trust verification rules, and practical scam identification checklists.`,
};

export async function processChatRequest(reqBody: ChatRequest) {
  const {
    messages,
    model = "gemini-3.1-flash-lite",
    useSearch = false,
    rolePersona = "threat_hunter",
  } = reqBody;

  if (!messages || !Array.isArray(messages) || messages.length === 0) {
    throw new Error("Invalid request: messages array is required.");
  }

  const ai = getAiClient();
  const systemInstruction = SYSTEM_INSTRUCTIONS[rolePersona] || SYSTEM_INSTRUCTIONS.threat_hunter;

  if (ai) {
    // Map multi-turn conversation history for the model
    const contents = messages.map((m) => ({
      role: m.role,
      parts: [{ text: m.text }],
    }));

    // Target model with graceful fallback to gemini-3.1-flash-lite
    const modelsToTry = model === "gemini-3.1-flash-lite" 
      ? ["gemini-3.1-flash-lite"] 
      : [model, "gemini-3.1-flash-lite"];

    for (const activeModel of modelsToTry) {
      try {
        let response: any = null;
        let isGrounded = false;

        // Try with Google Search Grounding if requested
        if (useSearch) {
          try {
            response = await ai.models.generateContent({
              model: activeModel,
              contents,
              config: {
                systemInstruction,
                tools: [{ googleSearch: {} }],
              },
            });
            isGrounded = true;
          } catch (searchErr: any) {
            console.warn(`Search grounding unavailable on ${activeModel} (${searchErr?.message || searchErr}), retrying directly with Gemini...`);
          }
        }

        // Direct call without search if search wasn't requested or failed/rate-limited
        if (!response) {
          response = await ai.models.generateContent({
            model: activeModel,
            contents,
            config: {
              systemInstruction,
            },
          });
        }

        const responseText = response.text || "No response generated by model.";

        // Extract search grounding metadata and citations if available
        const groundingChunks = response.candidates?.[0]?.groundingMetadata?.groundingChunks;
        const webSources: { uri: string; title: string }[] = [];

        if (groundingChunks && Array.isArray(groundingChunks)) {
          for (const chunk of groundingChunks) {
            if (chunk.web?.uri) {
              webSources.push({
                uri: chunk.web.uri,
                title: chunk.web.title || chunk.web.uri,
              });
            }
          }
        }

        const uniqueSources = Array.from(
          new Map(webSources.map((s) => [s.uri, s])).values()
        ).slice(0, 5);

        return {
          success: true,
          text: responseText,
          sources: uniqueSources,
          model: activeModel,
          groundedWithGoogleSearch: isGrounded && uniqueSources.length > 0,
        };
      } catch (err: any) {
        console.warn(`Gemini Chat error with ${activeModel}:`, err?.message || err);
      }
    }
  }

  // Robust Local Fallback when API key is unavailable or all remote calls fail
  const lastUserMsg = messages[messages.length - 1]?.text || "";
  return generateLocalChatFallback(lastUserMsg, rolePersona, model);
}

function generateLocalChatFallback(
  userQuery: string,
  rolePersona: "threat_hunter" | "incident_responder" | "cyber_advisor",
  modelName: string
) {
  const queryLower = userQuery.toLowerCase();

  let fallbackResponse = "";
  if (rolePersona === "incident_responder" || queryLower.includes("clicked") || queryLower.includes("hacked")) {
    fallbackResponse = `### 🚨 Emergency Incident Response Protocol

**Immediate Action Checklist:**
1. **Sever Connection:** Disconnect your device from Wi-Fi and mobile data immediately if an executable was downloaded.
2. **Lock Credentials:** Navigate to your banking or account portal from a separate, secure device and change your primary password immediately.
3. **Terminate Active Sessions:** Select "Log out of all devices" in account security settings to revoke compromised tokens.
4. **Inspect MFA:** Ensure your 2-Factor Authentication wasn't modified to route OTP codes to an unknown number.
5. **Contact Fraud Department:** Call your bank using the official phone number printed on the back of your debit/credit card.`;
  } else if (rolePersona === "threat_hunter" || queryLower.includes("domain") || queryLower.includes("url") || queryLower.includes("phish")) {
    fallbackResponse = `### 🛡️ Threat Hunter Forensic Assessment

**Deception Pattern Breakdown:**
- **Domain Anomaly:** Attackers frequently register ephemeral domains (often using \`.xyz\`, \`.top\`, or hyphenated lookalikes) within hours of launching smishing blasts.
- **Urgency Mechanism:** Threat actors employ artificial scarcity or consequence (e.g. "account locked in 24 hours", "package customs fee due") to bypass critical cognitive filters.
- **Safe Verification Rule:** Never click hyperlinks contained in unprompted communications. Always access services directly by typing their authoritative domain into your browser.`;
  } else {
    fallbackResponse = `### 🧠 Zero-Trust Security Advisory

When evaluating any suspicious message or request:
1. **Source Authenticity:** Look at the actual email sender address or SMS origin number, not just the display name.
2. **Channel Integrity:** Legitimate banks and government agencies will never ask for one-time passwords (OTPs), PINs, or wire transfers via text.
3. **Quishing Awareness:** Be extremely cautious of QR codes posted on public meters or sent via invoice attachments, as they bypass typical text-based email filters.`;
  }

  return {
    success: true,
    text: fallbackResponse,
    sources: [
      {
        uri: "https://www.cisa.gov/secure-our-world",
        title: "CISA Cybersecurity & Infrastructure Security Guide",
      },
      {
        uri: "https://consumer.ftc.gov/articles/how-recognize-and-avoid-phishing-scams",
        title: "Federal Trade Commission: How to Recognize Phishing",
      },
    ],
    model: modelName,
    groundedWithGoogleSearch: false,
    note: "Response served via ScamShield Defensive Threat Knowledge Base.",
  };
}
